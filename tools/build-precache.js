'use strict';
/* Regenerates www/precache-manifest.js and www/version.json (same idea as OIM Wazira):
   - lists every file the phone keeps (all of www/ except the files excluded below)
   - version = package.json version + short content hash, so a phone always gets a consistent new copy.
   Run: node tools/build-precache.js   (npm run dist / npm test run it automatically) */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const WWW = path.join(ROOT, 'www');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const EXCLUDE = [/^version\.json$/, /^sw\.js$/, /^setup\.html$/, /^phone\.html$/, /^precache-manifest\.js$/, /(^|\/)\./, /\.map$/, /(^|\/)Thumbs\.db$/i, /\.md$/i, /icon-1024\.png$/];
const CORE = ['./', './index.html', './precache-manifest.js', './manifest.webmanifest', './favicon.ico', './assets/css/app.css', './assets/fonts/fonts.css',
  './assets/js/i18n.js', './assets/js/core.js', './assets/js/charts.js', './assets/js/app.js', './assets/icons/icon-192.png', './assets/icons/apple-touch-icon-180.png'];

function walk(dir, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    const rel = path.relative(WWW, full).split(path.sep).join('/');
    if (EXCLUDE.some(r => r.test(rel))) continue;
    if (e.isDirectory()) walk(full, out); else out.push(rel);
  }
  return out;
}

const files = walk(WWW, []).sort();
const hash = crypto.createHash('sha256');
for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(WWW, f))); }
const version = pkg.version + '-' + hash.digest('hex').slice(0, 10);
const assets = files.map(f => './' + f).filter(f => !CORE.includes(f));
let bytes = 0; files.forEach(f => { bytes += fs.statSync(path.join(WWW, f)).size; });

const out = '/* Dashboard Cuaca Aziz - generated by tools/build-precache.js. Do not edit by hand. */\n' +
  'self.APP_VERSION = ' + JSON.stringify(version) + ';\n' +
  'self.APP_CORE = ' + JSON.stringify(CORE) + ';\n' +
  'self.APP_ASSETS = ' + JSON.stringify(assets).replace(/","/g, '",\n"') + ';\n';
fs.writeFileSync(path.join(WWW, 'precache-manifest.js'), out);
fs.writeFileSync(path.join(WWW, 'version.json'), JSON.stringify({ version, files: files.length, bytes, built: new Date().toISOString() }, null, 2));
console.log('precache: ' + files.length + ' files, ' + (bytes / 1048576).toFixed(2) + ' MB, version ' + version);
